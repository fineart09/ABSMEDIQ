// Helper: deterministic pseudo-random generator based on seed
function seeded(seed) {
  let x = Math.sin(seed) * 10000;
  return x - Math.floor(x);
}

function randomSegment(seed) {
  const segments = ['ลูกค้าทั่วไป', 'ลูกค้าประจำ', 'ลูกค้าพิเศษ', 'ลูกค้า VIP'];
  const idx = Math.floor(seeded(seed) * segments.length);
  return segments[idx];
}

function randomDiscount(seed) {
  // 0–30%, bias slightly toward smaller discounts
  const r = seeded(seed * 3.14159);
  return String(Math.round(Math.pow(r, 0.6) * 30));
}

